-- MAGIC ## B. Migration Tracker Structure
-- MAGIC
-- MAGIC Maintain a single source of truth (SSOT): a spreadsheet or a Delta table surfaced via a simple dashboard. Keep ad-hoc notes in notebooks, but all authoritative status lives in the tracker.
-- MAGIC
-- MAGIC Recommended tabs/views include:
-- MAGIC - Overview (scope, goals, statuses, owners)
-- MAGIC - Artifacts (SQL snippets, scripts, validations, UCX runs)
-- MAGIC - Validations (parity checks, permissions, functional tests)
-- MAGIC - UCX Runs (assessments, dry-runs, execution summaries)
-- MAGIC - Issues & Tickets (risks, blockers, remediation)
-- MAGIC - Change Log (audit trail of edits and state transitions)
-- MAGIC - Glossary (naming conventions, field definitions, status meanings)
-- MAGIC
-- MAGIC Core Fields
-- MAGIC - Identity & Ownership: artifact_id, type, area/domain, owner, stakeholders.
-- MAGIC - Timing & Environment: created_ts, updated_ts, environment (dev/stage/prod), workspace.
-- MAGIC - Object Paths: source_path (legacy catalog/schema/object), target_uc_path (catalog.schema.object), workspace_context.
-- MAGIC - Change Summary: concise rationale and impact; include deltas vs. original.
-- MAGIC - Evidence Links: code (notebook/script/PR), logs (validation/UCX), reports (HTML/JSON), job run URLs.
-- MAGIC - Validation & Risk: validation_status (pass/fail/partial), severity (low/med/high), dependencies.
-- MAGIC - Actionability: next_action, due_date, ticket_link (Jira/ServiceNow), reviewer.

