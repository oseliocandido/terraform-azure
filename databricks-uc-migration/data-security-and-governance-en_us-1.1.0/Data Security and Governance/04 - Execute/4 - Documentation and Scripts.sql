-- MAGIC %md
-- MAGIC ## C. Best Practices for Capturing Artifacts
-- MAGIC
-- MAGIC Generally recommended practices include:
-- MAGIC
-- MAGIC - **Capture at the point of change:** add entries as work is executed (not at the end of the day) and include `created_ts` and `owner`
-- MAGIC - **Always fully qualify references:** use workspace + `schema.object` notation for legacy HMS references, and `catalog.schema.object` for UC-side snippets, summaries, and evidence to avoid ambiguity.
-- MAGIC - **Keep artifacts atomic:** one logical change per row (for example, one grant set, one view refactor) to simplify validation and rollback.
-- MAGIC - **Record rationale and impact:** a concise explanation of why the change was made and expected downstream effects.
-- MAGIC - **Link durable evidence:** use stable notebook/job permalinks, DBFS paths, and repo commit/PR URLs; avoid ephemeral preview links.
-- MAGIC - **Version and diff:** attach pre/post references (commit hash, view definition diffs, config deltas) to make audits fast.
-- MAGIC - **Redact sensitive data:** never store secrets or PII; instead link to secret scopes or external locations.
-- MAGIC - **Standardize naming/tags:** adhere to controlled vocabularies for type, status, environment, and consistent artifact IDs.
-- MAGIC - **Validate then record:** include the validation result (row counts, permission parity, functional checks) with direct evidence links.
-- MAGIC - **Cross-link related work:** reference snippet_id, script_id, validation_id, ucx_run_id where applicable to enable traceability.
-- MAGIC - **Enforce review workflow:** require reviewer and block transitions to scheduled/deployed until required evidence is present.
-- MAGIC - **Ensure accessibility:** verify that all links resolve for stakeholder groups (domain teams, platform, security).
-- MAGIC - **Automate where possible:** ingest UCX outputs, write validation job results back, and prefill fields by target_uc_path.
-- MAGIC - **Use templated sections:** keep SQL/code blocks and tracker notes consistently formatted for readability.
-- MAGIC - **Handle failures explicitly:** create tickets for errors/warnings, set severity, and capture next_action with target dates.

